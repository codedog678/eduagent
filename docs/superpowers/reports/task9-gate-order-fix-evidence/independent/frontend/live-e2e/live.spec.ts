import { readFileSync } from 'node:fs'
import { expect, test } from '@playwright/test'

const own = '/tmp/m3-task9-spec-independent'
const fixture = JSON.parse(readFileSync(`${own}/live-fixture.json`, 'utf8'))

test('production assets with real PG API: pagination filters health audit and no mutations', async ({ page }, info) => {
  const requests: string[] = []
  const errors: string[] = []
  page.on('request', req => { if (req.url().includes('/ops-api/')) requests.push(req.method()) })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/ops/#/policies')
  await expect(page.getByRole('heading', { name: 'Policies', exact: true })).toBeVisible()
  const list = page.getByRole('region', { name: '策略证据列表' })
  await expect(list.locator('.ant-table-row')).toHaveCount(50)
  await page.getByRole('button', { name: /下一页/ }).click()
  await expect(page.getByText('第 2 页', { exact: true })).toBeVisible()
  await expect(list.locator('.ant-table-row')).toHaveCount(7)
  await page.getByLabel('策略状态').click()
  await page.getByTitle('canary', { exact: true }).click()
  await expect(list.locator('.ant-table-row')).toHaveCount(1)
  await expect(page.getByText('第 1 页', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: `查看策略 ${fixture.old_deployment_id}` }).click()
  const detail = page.getByRole('region', { name: '策略版本详情' })
  await expect(detail.getByText(fixture.old_policy_hash, { exact: true })).toBeVisible()
  await expect(detail.getByText('fail', { exact: true })).toBeVisible()
  await expect(detail.getByText('health_rollback', { exact: true })).toBeVisible()
  await expect(detail.getByText(fixture.window_id, { exact: false })).toBeVisible()
  await expect(detail.getByText('版本 2', { exact: false })).toBeVisible()
  await expect(detail.getByText('当前版本 3', { exact: false })).toBeVisible()
  await page.locator('.ops-policy-status').first().hover()
  await expect(page.getByRole('tooltip').first()).toContainText('只读状态')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth + 1)).toBe(true)
  if (info.project.name === 'mobile') {
    const table = list.locator('.ant-table-content')
    expect(await table.evaluate(el => el.scrollWidth > el.clientWidth)).toBe(true)
    await table.hover()
    await page.mouse.wheel(900, 0)
    await expect.poll(() => table.evaluate(el => el.scrollLeft)).toBeGreaterThan(0)
    await page.mouse.wheel(-900, 0)
  }
  await page.screenshot({ path: `${own}/screenshots/live-policy-${info.project.name}.png`, fullPage: true })
  await page.getByRole('tab', { name: '健康窗口' }).click()
  await expect(list.getByText('fail', { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: '审计时间线' }).click()
  await expect(list.getByText('health_rollback', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '重置', exact: true }).click()
  await page.getByRole('tab', { name: '部署', exact: true }).click()
  await page.getByLabel('策略环境').click()
  await page.getByTitle('production', { exact: true }).click()
  await expect(list.locator('.ant-table-row')).toHaveCount(1)
  await page.getByLabel('策略状态').click()
  await page.getByTitle('canary', { exact: true }).click()
  await expect(list.getByText('没有符合条件的策略证据')).toBeVisible()
  expect(requests.every(method => method === 'GET')).toBe(true)
  await expect(page.getByRole('button', { name: /晋升|回滚|冻结|发布|删除/ })).toHaveCount(0)
  expect(errors).toEqual([])
})

test('real rollback old candidate Run trace links frozen version while new Run stays stable', async ({ page }, info) => {
  await page.goto(`/ops/#/trace/${fixture.old_run_id}`)
  const identity = page.getByRole('region', { name: '运行策略绑定' })
  await expect(identity.getByText('candidate · rehearsal')).toBeVisible()
  await expect(identity.getByText(fixture.old_policy_hash, { exact: true })).toBeVisible()
  await page.screenshot({ path: `${own}/screenshots/live-trace-${info.project.name}.png`, fullPage: true })
  await identity.getByRole('link', { name: fixture.old_deployment_id, exact: true }).click()
  const detail = page.getByRole('region', { name: '策略版本详情' })
  await expect(detail.getByText('版本 2', { exact: false })).toBeVisible()
  await expect(detail.getByText('当前版本 3', { exact: false })).toBeVisible()
  await page.goto(`/ops/#/trace/${fixture.new_run_id}`)
  await expect(identity.getByText('stable · rehearsal')).toBeVisible()
  await expect(identity.getByText(fixture.new_policy_hash, { exact: true })).toBeVisible()
  await expect(identity.getByRole('link', { name: fixture.current_deployment_id, exact: true })).toBeVisible()
})
